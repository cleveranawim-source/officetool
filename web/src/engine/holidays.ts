export function publicHolidays(start: string, end: string): CalEvent[] {
  return KR.filter(([d]) => d >= start && d <= end).map(([d, name]) => ({
    id: `kr-${d}`,
    title: name,
    start: d,
    end: d,
    source: 'auto' as const,
  }));
}

/** 같은 날 같은 성격의 일정이 이미 캘린더에 있으면 자동 공휴일은 뺀다 */
export function mergeHolidays(events: CalEvent[], start: string, end: string): CalEvent[] {
  const hasHoliday = new Set(
    events.filter((e) => /공휴일|휴업|추석|설날|성탄|한글날|개천절|광복절|삼일절|현충일|어린이날|신정|부처님/.test(e.title)).map((e) => e.start),
  );
  return [...publicHolidays(start, end).filter((h) => !hasHoliday.has(h.start)), ...events];
}
