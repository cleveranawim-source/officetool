/** 매주 월요일 교직원 회의 (학기 중, 공휴일 빼고) */
function mondays(from: string, to: string): string[] {
  const out: string[] = [];
  for (let d = from; d <= to; d = addDays(d, 7)) if (weekdayIndex(d) === 0 && !holidayName(d)) out.push(d);
  return out;
}

